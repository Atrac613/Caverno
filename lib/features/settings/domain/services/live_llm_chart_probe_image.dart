/// The bar chart the Live LLM diagnostic's chart-reading probe shows a model.
///
/// Kept in its own file because it is generated data: a few hundred lines of
/// base64 next to the probe's logic would bury it, and this way the constant
/// has its own line budget rather than eating the service's.
///
/// ## What it is
///
/// A 640x481 PNG of a five-bar chart titled "Quarterly output by unit", with a
/// 0-100 y axis, gridlines every 20, and bars labelled Aster 41, Briar 78,
/// Cobalt 23, Dune 92, Ember 57.
///
/// The values are deliberately unmemorable and the labels deliberately not
/// words a model would associate with an ordering. A chart question is easy to
/// guess -- "which bar is tallest?" has five answers and a plausible prior --
/// so the probe pairs this with a no-image control arm, and the picture only
/// counts as read when it beats the guess.
///
/// ## Why this size
///
/// Measured, not chosen. The quadrant vision probe in the same service was a
/// 64px image on the theory that solid colors survive downscaling, and it made
/// a vision-capable model look blind. This one was measured over a real
/// endpoint (qwen3.8-27b-vision) at 600, 1100 and 1700 pixels wide: all three
/// answered every question correctly, and the no-image control answered none.
/// 640px is the smallest width above the smallest measured pass, so the probe
/// reports the model's limit rather than the harness's. Do not shrink it
/// without re-measuring.
///
/// PNG rather than JPEG, which would be a third the size: a lossy encoder puts
/// artifacts on exactly the thin axis lines and small labels the probe asks
/// the model to read, and the probe is meant to measure the model.
///
/// ## Regenerating
///
/// Draw the chart and rasterize one page with the tools under
